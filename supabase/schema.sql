-- HOA Secure Vote - Supabase PostgreSQL schema
-- Run this entire file once in Supabase Dashboard -> SQL Editor.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null,
  password_hash text not null,
  role text not null check (role in ('admin','voter')),
  full_name text not null,
  block text,
  lot text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists users_username_lower_uq on public.users (lower(username));
create index if not exists idx_users_role on public.users(role);
create index if not exists idx_users_block_lot on public.users(block,lot);

create table if not exists public.sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  csrf_token text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_sessions_user on public.sessions(user_id);
create index if not exists idx_sessions_expiry on public.sessions(expires_at);

-- Voters are restricted to one active login session at a time.
-- The user-row lock serializes concurrent login attempts so two devices cannot both
-- create sessions at the same moment. Admin accounts are intentionally exempt.
create or replace function public.hoa_enforce_single_voter_session()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  account_role text;
begin
  select role into account_role
  from public.users
  where id = NEW.user_id
  for update;

  if account_role is null then
    raise exception 'User account not found.';
  end if;

  -- Remove this user's expired sessions before checking for an active one.
  delete from public.sessions
  where user_id = NEW.user_id
    and expires_at <= now();

  if account_role = 'voter' and exists (
    select 1 from public.sessions
    where user_id = NEW.user_id
      and expires_at > now()
  ) then
    raise exception 'This voter account is already signed in on another device. Please log out there first before signing in here.';
  end if;

  return NEW;
end;
$$;

drop trigger if exists trg_single_voter_session on public.sessions;
create trigger trg_single_voter_session
before insert on public.sessions
for each row execute function public.hoa_enforce_single_voter_session();

-- Migration cleanup: remove expired sessions and, if an older deployment already
-- allowed multiple voter sessions, keep only the newest active session per voter.
delete from public.sessions where expires_at <= now();
with ranked_voter_sessions as (
  select s.token_hash,
         row_number() over (partition by s.user_id order by s.created_at desc, s.token_hash desc) as rn
  from public.sessions s
  join public.users u on u.id = s.user_id
  where u.role = 'voter'
)
delete from public.sessions s
using ranked_voter_sessions r
where s.token_hash = r.token_hash
  and r.rn > 1;

create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  ip text not null,
  username text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists idx_login_attempts_ip_time on public.login_attempts(ip,attempted_at);

create table if not exists public.elections (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  status text not null default 'draft' check (status in ('draft','open','closed')),
  created_by bigint not null references public.users(id),
  opened_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_elections_status on public.elections(status);
create unique index if not exists one_open_election_uq on public.elections ((status)) where status='open';

create table if not exists public.positions (
  id bigint generated by default as identity primary key,
  election_id bigint not null references public.elections(id) on delete cascade,
  title text not null,
  seats integer not null default 1 check (seats between 1 and 50),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(election_id,title)
);
create index if not exists idx_positions_election on public.positions(election_id,sort_order);

create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  position_id bigint not null references public.positions(id) on delete cascade,
  full_name text not null,
  statement text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(position_id,full_name)
);
create index if not exists idx_candidates_position on public.candidates(position_id,sort_order);

-- Identity is deliberately stored separately from anonymous ballot choices.
create table if not exists public.voter_participation (
  user_id bigint not null references public.users(id) on delete restrict,
  election_id bigint not null references public.elections(id) on delete cascade,
  voted_at timestamptz not null default now(),
  receipt_code text not null unique,
  primary key(user_id,election_id)
);
create index if not exists idx_participation_election on public.voter_participation(election_id,voted_at);

create table if not exists public.ballots (
  id uuid primary key,
  election_id bigint not null references public.elections(id) on delete cascade,
  submitted_at timestamptz not null default now()
);
create index if not exists idx_ballots_election on public.ballots(election_id,submitted_at);

create table if not exists public.ballot_votes (
  ballot_id uuid not null references public.ballots(id) on delete cascade,
  election_id bigint not null references public.elections(id) on delete cascade,
  position_id bigint not null references public.positions(id) on delete cascade,
  candidate_id bigint not null references public.candidates(id) on delete cascade,
  primary key(ballot_id,candidate_id)
);
create index if not exists idx_ballot_votes_results on public.ballot_votes(election_id,position_id,candidate_id);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id bigint references public.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_audit_time on public.audit_log(created_at);

