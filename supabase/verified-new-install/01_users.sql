create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null,
  password_hash text not null,
  role text not null check (role in ('admin','voter')),
  full_name text not null,
  block text,
  lot text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.users enable row level security;
revoke all on table public.users from anon, authenticated;
grant select, insert, update, delete on table public.users to service_role;
grant usage, select on all sequences in schema public to service_role;

create unique index if not exists users_username_lower_uq on public.users (lower(username));
create index if not exists idx_users_role on public.users(role);
create index if not exists idx_users_block_lot on public.users(block,lot);
-- Existing application rules assume one voter account per eligible block/lot.
create unique index if not exists users_voter_unit_uq
  on public.users ((lower(btrim(block))), (lower(btrim(lot))))
  where role = 'voter';

select case when exists(
  select 1 from pg_catalog.pg_class c
  where c.oid = to_regclass('public.users') and c.relrowsecurity
  and not has_table_privilege('anon',c.oid,'SELECT')
  and not has_table_privilege('authenticated',c.oid,'SELECT')
) then 'PASS 1A: users table created and protected'
  else 'FAIL 1A: check users table/RLS/permissions' end as step_result;
