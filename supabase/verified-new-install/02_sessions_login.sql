-- HOA ELECTION: STEP 1B / 5: SESSIONS + LOGIN ATTEMPTS
-- Run after 01_Users.sql; execute the entire file.

create table if not exists public.sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  csrf_token text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
alter table public.sessions enable row level security;
revoke all on table public.sessions from anon, authenticated;
grant select, insert, update, delete on table public.sessions to service_role;
create index if not exists idx_sessions_user on public.sessions(user_id);
create index if not exists idx_sessions_expiry on public.sessions(expires_at);

create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  ip text not null,
  username text not null,
  attempted_at timestamptz not null default now()
);
alter table public.login_attempts enable row level security;
revoke all on table public.login_attempts from anon, authenticated;
grant select, insert, update, delete on table public.login_attempts to service_role;
create index if not exists idx_login_attempts_ip_time on public.login_attempts(ip,attempted_at);
create index if not exists idx_login_attempts_ip_user_time on public.login_attempts(ip,username,attempted_at);
grant usage, select on all sequences in schema public to service_role;

select case when
  (select count(*) from pg_class where oid in
    (to_regclass('public.sessions'),to_regclass('public.login_attempts')) and relrowsecurity)=2
  then 'PASS 1B: sessions + login_attempts created with RLS'
  else 'FAIL 1B: check tables and RLS' end as step_result;
