create table if not exists public.elections (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  status text not null default 'draft' check (status in ('draft','open','closed')),
  created_by bigint not null references public.users(id),
  opened_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.elections enable row level security;
revoke all on table public.elections from anon, authenticated;
grant select, insert, update, delete on table public.elections to service_role;
create index if not exists idx_elections_status on public.elections(status);
create unique index if not exists one_open_election_uq on public.elections ((status)) where status='open';

create table if not exists public.positions (
  id bigint generated by default as identity primary key,
  election_id bigint not null references public.elections(id) on delete cascade,
  title text not null,
  seats integer not null default 1 check (seats between 1 and 50),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(election_id,title)
);
alter table public.positions enable row level security;
revoke all on table public.positions from anon, authenticated;
grant select, insert, update, delete on table public.positions to service_role;
create index if not exists idx_positions_election on public.positions(election_id,sort_order);

create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  position_id bigint not null references public.positions(id) on delete cascade,
  full_name text not null,
  statement text,
  photo_path text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(position_id,full_name)
);
alter table public.candidates add column if not exists photo_path text;
alter table public.candidates enable row level security;
revoke all on table public.candidates from anon, authenticated;
grant select, insert, update, delete on table public.candidates to service_role;
create index if not exists idx_candidates_position on public.candidates(position_id,sort_order);
grant usage, select on all sequences in schema public to service_role;

select case when
  (select count(*) from pg_class where oid in
    (to_regclass('public.elections'),to_regclass('public.positions'),to_regclass('public.candidates'))
    and relrowsecurity)=3
  then 'PASS 1C: elections + positions + candidates created with RLS'
  else 'FAIL 1C: check tables and RLS' end as step_result;
