create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id bigint references public.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.audit_log enable row level security;
revoke all on table public.audit_log from anon, authenticated;
grant select, insert, update, delete on table public.audit_log to service_role;
create index if not exists idx_audit_time on public.audit_log(created_at);
grant usage, select on all sequences in schema public to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('candidate-photos','candidate-photos',false,5242880,
  array['image/jpeg','image/png','image/webp']::text[])
on conflict (id) do update set
  name=excluded.name,
  public=false,
  file_size_limit=excluded.file_size_limit,
  allowed_mime_types=excluded.allowed_mime_types;

select case when
  exists(select 1 from pg_class where oid=to_regclass('public.audit_log') and relrowsecurity)
  and exists(select 1 from storage.buckets where id='candidate-photos' and public=false)
  then 'PASS 1E: audit_log + private candidate-photos bucket ready'
  else 'FAIL 1E: check audit_log and photo storage bucket' end as step_result;
